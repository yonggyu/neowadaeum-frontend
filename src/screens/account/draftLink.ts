import { authoringDraftPath } from '../../routes/routes'

/**
 * 작품에서 원고로 가는 길 (`MyStoryItem.draftId`, backend #340 · 정정본 §13-66).
 *
 * 두 화면이 같은 판정을 한다 — `MyStoriesScreen` 의 "이어서 작성" 과 `MyStoryReviewScreen` 의
 * 반려 패널이다. **판정이 하나뿐이라는 것이 이 파일의 이유다**: 두 곳에서 각각
 * `draftId !== null` 을 적으면 언젠가 한 곳이 빠지고, 그 한 곳이 **없는 원고로 보내는 버튼**을
 * 그린다. 눌러 보기 전까지 그 버튼은 있는 것처럼 보인다.
 *
 * **제목으로 짝짓지 않는다.** 작품과 원고를 잇는 규칙은 서버가 갖는다 — 같은 제목의 원고가
 * 둘이면 화면이 조용히 남의 것을 연다 (§13-66). 그래서 여기 오는 값은 서버가 준 `draftId`
 * 하나이고, 없으면 없는 것이다.
 */

/**
 * 이어서 쓸 원고의 경로. **없으면 `null` 이고, 그때 화면은 버튼을 그리지 않는다.**
 *
 * `draftId` 가 `null` 인 작품이 실제로 있다 — 미리보기가 만든 임시 작품은 원고와 연결되지
 * 않은 채 파기를 기다린다 (§13-5 · §13-37). 그 줄에 아무 원고나 붙이는 것보다 **없다고
 * 말하는 편이 사실이다.**
 *
 * 빈 문자열도 `null` 과 같이 다룬다. 계약의 `draftId` 는 uuid 이므로 그것은 계약 밖의 값이고,
 * 그대로 이으면 `/authoring/drafts/` 라는 **없는 경로로 보내는 버튼**이 된다 — 이 함수가
 * 막으려던 것과 같은 일이다.
 */
export function draftPathOf(draftId: string | null): string | null {
  if (draftId === null || draftId === '') {
    return null
  }
  return authoringDraftPath(draftId)
}

/**
 * 원고가 없을 때 화면이 그 자리에 적는 것.
 *
 * **빈 자리를 두지 않는다.** 버튼만 지우면 작성자는 자기 작품만 다르게 보이는 이유를 알
 * 방법이 없고, 비어 있는 화면은 돌아가는 것처럼 보인다 (CLAUDE.md — 개발 루프).
 *
 * **왜 없는지를 단정하지 않는다.** 계약이 `null` 의 예로 미리보기 작품을 들었을 뿐이며
 * (§13-5), 원인을 화면이 하나로 못박으면 다른 이유로 `null` 인 날 화면이 거짓을 말한다.
 */
export const NO_DRAFT_NOTICE =
  '이 작품에는 이어서 쓸 원고가 없습니다. 원고 없이 만들어진 작품이라 여기서 열 원고가 없어요.'
