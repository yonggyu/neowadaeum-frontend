/**
 * 재검토 요청이 말하는 것 (계약 `appealStorySuspension`, 정정본 §13-59).
 *
 * **가운데 줄이 이 문구의 이유다.** 정지된 작품은 이미 인간 검수 큐에 있고, 이 요청이
 * 바꾸는 것은 기록과 검수 큐의 신호뿐이다 — 화면이 "재검토 중" 으로 상태를 바꿔 그리면
 * 작성자가 검수 결과를 되돌리는 것처럼 보인다 (I-8).
 *
 * **복구를 약속하지 않는다.** 계약이 `202` 의 설명에 그렇게 적었다: *"접수됨. 복구를
 * 약속하지 않는다 — 판정은 사람이 한다."*
 */
export const STORY_APPEAL_NOTICE: readonly string[] = [
  '요청과 사유는 검수자에게 전달됩니다',
  '이 요청만으로 작품의 상태가 달라지지는 않습니다',
  '판정은 사람이 합니다. 차례가 앞당겨지지는 않습니다',
]

/**
 * 사유의 길이 상한 — **계약이 정한 값**이다 (`AppealRequest.maxLength`).
 *
 * 생성 타입이 이 값을 나르지 못해 여기 적는다 (F-2 의 대상은 타입이다). **정본은 계약**이고
 * 초과는 서버가 `400` 으로 거절한다 — 여기 있는 것은 눌러 보기 전에 알려 주는 안내다.
 */
export const APPEAL_REASON_MAX = 500

/**
 * 지금 보낼 수 있는 사유인가.
 *
 * 계약이 `minLength: 1` 이자 **필수**로 정했다 — 정지된 작품은 이미 큐에 있으므로 사유 없는
 * 요청은 검수자에게 아무것도 주지 않고, 그러면 이 경로는 큐를 다시 채우는 버튼일 뿐이다.
 */
export function canSubmitAppeal(reason: string): boolean {
  const trimmed = reason.trim()
  return trimmed !== '' && trimmed.length <= APPEAL_REASON_MAX
}
