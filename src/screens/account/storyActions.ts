/**
 * 되돌릴 수 없는 두 동작이 **말하는 것** — 작품 삭제와 재검토 요청 (와이어프레임 3f · 6c).
 *
 * 문구를 화면에서 떼어 여기 두는 이유는 `accountSettings.ts` 의 탈퇴 문구와 같다: **어디를
 * 강조하고 무엇을 말하는가가 디자인이 아니라 내용**이고, 계약이 정한 사실과 어긋나는 순간
 * 그것은 문구 실수가 아니라 거짓말이 된다. 그래서 단위 테스트가 이 상수를 붙잡는다.
 *
 * 두 문구를 한 파일에 둔 것은 모양이 닮아서가 아니라 **같은 화면(3f)의 같은 자리**에서
 * 갈리기 때문이다 — 정지된 작품 앞에서 작성자가 고르는 두 갈래가 이 둘이다.
 */

/**
 * 삭제 확인이 말하는 것 (계약 `deleteStory`, 정정본 §13-58).
 *
 * **"완전히 삭제됩니다" 는 거짓말이다.** 계약이 그 자리에 정확히 무엇이 남는지를 적었다 —
 * 세션 · 턴 · GameState 스냅샷 · 엔딩 도달률 · 신고 · 검수 이력은 지워지지 않는다. 그것은
 * 플레이한 사람들과 검수의 기록이지 작성자의 것이 아니기 때문이다. 진행 중이던 세션도
 * 사라지지 않는다: 이어갈 수 없을 뿐 읽던 내용은 그대로 열린다 (`423 STORY_SUSPENDED`).
 *
 * **되돌릴 수 없다는 것은 단정한다.** 복구 경로가 계약에 없고, 다시 내려면 원고를 새로
 * 제출해야 하며 그 제출은 **새 작품**이 된다 (B-56). 탈퇴 문구에서 *"다시 로그인할 수
 * 없습니다"* 한 줄만 단정한 것과 같은 기준이다 — 확실한 것만 단정한다.
 *
 * 순서는 **작성자가 겪는 순서**다: 무엇이 사라지고 · 읽던 사람은 어떻게 되고 · 무엇이 남고 ·
 * 다시 내려면 어떻게 하는가 · 되돌릴 수 없다.
 */
