  '진행 중이던 이용자는 읽던 내용만 볼 수 있고, 새 턴을 만들 수 없습니다',
  '플레이 기록과 신고 · 검수 이력은 남습니다',
  '다시 내려면 원고를 새로 제출합니다. 그 제출은 새 작품이 됩니다',
  '되돌릴 수 없습니다',
